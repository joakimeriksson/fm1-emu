#!/usr/bin/env python3
"""Generate crates/fm1-isa/src/pi32v2.rs from pi32v2-isa's table (https://github.com/jvitkauskas/pi32v2-isa, MIT-0).

The table's 1171 forms, each with its encoding (mask and value in this emulator's little-endian window: the
first 16-bit word in bits 0..15) and its fields (bit positions in that window, most significant first, and how
the raw value reads: register, pair, immediate, enum, ...). fm1-core runs the forms it has semantics for
(`pi32v2_exec.rs`) when the table decodes a word as one of them; the rest stay with fm1-isa's own classes.

    python3 tools/gen_pi32v2.py --isa ../pi32v2-isa
"""
import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KINDS = {"gpr": "Gpr", "gpr_lo": "GprLo", "gpr_hi": "GprHi", "pair": "Pair", "pair_regs": "PairRegs", "bit": "Bit",
         "invbit": "InvBit", "modimm": "Modimm", "enum": "Enum", "uimm": "Uimm", "simm": "Simm", "rmask": "Rmask",
         "rlist4": "Rlist4", "sr": "Sr", "srmask": "Srmask"}


def window_bit(nbits, pos):
    """The bit of the little-endian window for the table's bit pos (0 = the first word's top bit)."""
    return 16 * (pos // 16) + 15 - pos % 16


def to_window(nbits, v):
    out = 0
    for pos in range(nbits):
        if v >> (nbits - 1 - pos) & 1:
            out |= 1 << window_bit(nbits, pos)
    return out


def rs(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--isa", required=True, type=Path)
    ap.add_argument("--out", default=ROOT / "crates/fm1-isa/src/pi32v2.rs", type=Path)
    a = ap.parse_args()
    sys.path.insert(0, str(a.isa))
    from pi32v2isa import table  # noqa: E402
    t = table.load(a.isa / "isa/pi32v2.toml")
    rev = subprocess.run(["git", "-C", str(a.isa), "rev-parse", "--short", "HEAD"], capture_output=True,
                         text=True).stdout.strip() or "unknown"
    lines = [
        "// Generated by tools/gen_pi32v2.py from pi32v2-isa's isa/pi32v2.toml",
        f"// (https://github.com/jvitkauskas/pi32v2-isa, MIT-0) at {rev}. Do not edit.",
        "use crate::pi32v2_table::{Field, Form, Kind};",
        "use crate::IsaEntry;",
        "",
        "/// Every form, in the table's order (decoding takes the first that matches).",
        "pub static FORMS: &[Form] = &[",
    ]
    consts, entries = [], []
    for k, i in enumerate(t.insns):
        nbits = 16 * len(i.words)
        fields = []
        for name, f in i.fields.items():
            bits = ", ".join(str(window_bit(nbits, p)) for p in i.field_bits(name))
            vals = ", ".join(rs(v) for v in f.values)
            za = f"Some({f.zero_as})" if f.zero_as is not None else "None"
            fields.append(f"Field {{ name: {rs(name)}, kind: Kind::{KINDS[f.kind]}, bits: &[{bits}], scale: {f.scale}, "
                          f"add: {f.add}, zero_as: {za}, invert: {str(bool(f.invert)).lower()}, values: &[{vals}] }}")
        lines.append(f"    Form {{ id: {rs(i.id)}, syntax: {rs(i.syntax)}, group: {rs(i.group)}, len: {2 * len(i.words)}, "
                     f"mask: {to_window(nbits, i.mask):#x}, value: {to_window(nbits, i.value):#x}, fields: &[")
        for fl in fields:
            lines.append(f"        {fl},")
        lines.append("    ] },")
        consts.append(f"    pub const {i.id.upper().replace('.', '_')}: usize = {k};")
        entries.append(f"    IsaEntry {{ name: {rs('pi:' + i.id)}, syntax: {rs(i.syntax)}, len: {2 * len(i.words)}, count: 0, "
                       f"mask: {to_window(nbits, i.mask):#x}, match_: {to_window(nbits, i.value):#x}, group: {rs(i.group)}, "
                       f"alt: &[], samples: &[], slots: &[] }},")
    lines += ["];", "", "/// Each form as a class of the emulator's decoder (`FORMS`' order; named `pi:` and the id).",
              "pub static ENTRIES: &[IsaEntry] = &["] + entries + ["];", ""]
    lines += ["/// Each form's index in `FORMS`, by its id (`.` as `_`, upper case).", "pub mod id {"] + consts + ["}", ""]
    a.out.write_text("\n".join(lines))
    print(f"{len(t.insns)} forms -> {a.out}")


if __name__ == "__main__":
    main()
